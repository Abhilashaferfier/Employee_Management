import {
  Component,
  OnInit
} from '@angular/core';

import {
  UsersService
} from '../../../services/users.service';


// ======================================================
// USER INTERFACE
// ======================================================

export interface User {

  userId: string;

  firstName: string;

  lastName: string;

  email: string;

}


// ======================================================
// COMPONENT
// ======================================================

@Component({

  selector:
    'app-users',

  templateUrl:
    './users.component.html',

  styleUrls:
    ['./users.component.css']

})
export class UsersComponent
  implements OnInit {


  // ======================================================
  // USERS LIST
  // ======================================================

  users: User[] = [];


  // ======================================================
  // LOADING
  // ======================================================

  loading = false;


  // ======================================================
  // ERROR MESSAGE
  // ======================================================

  errorMessage = '';


  // ======================================================
  // CONSTRUCTOR
  // ======================================================

  constructor(

    private usersService:
      UsersService

  ) {}


  // ======================================================
  // NG ON INIT
  // ======================================================

  ngOnInit(): void {

    this.loadUsers();

  }


  // ======================================================
  // GET ALL USERS
  // ======================================================

  loadUsers(): void {

    // ----------------------------------------------------
    // START LOADING
    // ----------------------------------------------------

    this.loading = true;

    this.errorMessage = '';


    // ----------------------------------------------------
    // CALL API
    // ----------------------------------------------------

    this.usersService
      .getAllUsers()
      .subscribe({


        // =================================================
        // SUCCESS
        // =================================================

        next: (
          response: User[]
        ) => {

          console.log(
            'GET USERS RESPONSE:',
            response
          );


          // -----------------------------------------------
          // STORE USERS
          // -----------------------------------------------

          this.users =
            response || [];


          // -----------------------------------------------
          // STOP LOADING
          // -----------------------------------------------

          this.loading =
            false;

        },


        // =================================================
        // ERROR
        // =================================================

        error: (
          error: any
        ) => {

          console.error(
            'GET USERS ERROR:',
            error
          );


          // -----------------------------------------------
          // CLEAR USERS
          // -----------------------------------------------

          this.users =
            [];


          // -----------------------------------------------
          // ERROR MESSAGE
          // -----------------------------------------------

          this.errorMessage =

            error?.error?.message ||

            error?.error?.responseMessage ||

            error?.message ||

            'Unable to load users.';


          // -----------------------------------------------
          // STOP LOADING
          // -----------------------------------------------

          this.loading =
            false;

        }

      });

  }

}